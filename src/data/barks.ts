/** 暴躁老哥一边拆一边骂骂咧咧的随机台词（按怒气分级） */

// 平常拆包的碎碎念
export const BARKS_CALM = [
  '拆！', '开！', '下一个。', '哼。', '小意思。', '就这？', '区区纸箱。', '受死吧破箱子。',
  '给我裂开。', '老实点。', '哪个龟孙封的箱？', '又是你。',
];

// 连击上头时的暴躁话
export const BARKS_HOT = [
  '这胶带缠了八百层？！', '今天非拆穿你不可！', '纸箱也敢造反？！', '气死我了！',
  '快点开啊喂！', '啊啊啊拆烂你！', '别给我硬撑！', '手都拆抽筋了！', '到底装的什么玩意！',
];

// 超高连击的狂暴话
export const BARKS_RAGE = [
  '拆拆拆拆拆！！', '全都给我开！！', '世界都欠我一个快递！', '我就是拆箱之神！！',
  '挡我者拆！！', '停不下来了根本停不下来！',
];

// 拆出稀有/传说时的惊呼
export const BARKS_LUCKY = [
  '哟，这个有点东西。', '发了发了！', '欧皇附体！', '这玩意能卖不少。', '运气来了挡都挡不住。',
];

export function barkFor(combo: number): string[] {
  if (combo >= 50) return BARKS_RAGE;
  if (combo >= 15) return BARKS_HOT;
  return BARKS_CALM;
}
